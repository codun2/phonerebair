export function useI18n() {
  const lang = useCookie<'ar' | 'en'>('pr_lang', { default: () => 'ar', maxAge: 60 * 60 * 24 * 365 })
  const isEn = computed(() => lang.value === 'en')
  const t = (s: string) => (isEn.value ? (DICT[s] ?? s) : s)
  function toggle() { lang.value = isEn.value ? 'ar' : 'en' }
  return { lang, isEn, t, toggle }
}
